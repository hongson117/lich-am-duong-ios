test('Restore a valid backup and reject invalid input without data loss', async ({ page }) => {
  await page.getByRole('tab', { name: 'Tiện ích', exact: true }).click();
  const payload = { app: 'lich-am-duong', version: 2, memorials: [{ id: 'restore-fixture', name: 'Bà ngoại - phục hồi', relation: '', day: 15, month: 7, note: '', leapPolicy: 'regular', shortMonthPolicy: 'last-day', createdAt: '2026-01-01T00:00:00Z' }], personal: { favorites: [8], notes: { '8': 'Ghi chú từ bản sao lưu' }, reminders: { memorials: true, lunarDays: true, when: 'morning' } } };
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Khôi phục từ tệp sao lưu', exact: true }).click();
  await (await chooser).setFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(payload)) });
  await page.getByRole('button', { name: 'Bổ sung vào danh sách', exact: true }).click();
  await page.getByRole('tab', { name: 'Ngày giỗ', exact: true }).click();
  await expect(page.getByText('Bà ngoại - phục hồi', { exact: true })).toBeVisible();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('@lich-am-duong/data/v2')!));
  expect(stored.personal.notes['8']).toBe('Ghi chú từ bản sao lưu');
  expect(stored.personal.reminders.memorials).toBe(false);
  await page.getByRole('tab', { name: 'Tiện ích', exact: true }).click();
  const invalid = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Khôi phục từ tệp sao lưu', exact: true }).click();
  await (await invalid).setFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"app":"wrong"}') });
  await expect(page.getByText('Tệp sao lưu không hợp lệ.')).toBeVisible();
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('@lich-am-duong/data/v2')!));
  expect(after.memorials).toEqual(stored.memorials);
});
